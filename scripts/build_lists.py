#!/usr/bin/env python3
"""Скачивает источники из config/sources.json, переводит в правила geosite,
вычитает config/allowlist.txt, проверяет config/critical.txt и пишет
файлы данных для domain-list-community в <out>/data/<tag>.

Запуск: python3 scripts/build_lists.py --out build
"""
import argparse
import json
import os
import sys
import time
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import geolib  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def fetch(url, cache_dir):
    name = os.path.join(cache_dir, url.replace("://", "_").replace("/", "_"))
    if os.path.exists(name):
        with open(name, encoding="utf-8", errors="replace") as f:
            return f.read()
    last = None
    for attempt in range(4):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "xeno-adblock-lists"})
            with urllib.request.urlopen(req, timeout=120) as r:
                body = r.read().decode("utf-8", errors="replace")
            with open(name, "w", encoding="utf-8") as f:
                f.write(body)
            return body
        except Exception as e:  # сеть GitHub иногда отвечает 5xx
            last = e
            time.sleep(2 ** (attempt + 1))
    raise RuntimeError(f"download failed: {url}: {last}")


def apply_allowlist(entries, allow, log):
    """Удаляет правила, которые задевают разрешённые хосты."""
    allow_domains = geolib.Matcher([e for e in allow if e[0] == "domain"])
    allow_hosts = [v for _, v in allow]
    kept = []
    for typ, value in entries:
        reason = None
        if typ in ("domain", "full"):
            if allow_domains.match(value):
                reason = "inside allowlisted domain"
            elif ("full", value) in allow:
                reason = "allowlisted host"
            elif typ == "domain":
                parent_of = next((h for h in allow_hosts if h.endswith("." + value)), None)
                if parent_of:
                    reason = f"parent of allowlisted {parent_of}"
        else:
            m = geolib.Matcher([(typ, value)])
            hit = next((h for h in allow_hosts if m.match(h)), None)
            if hit:
                reason = f"matches allowlisted {hit}"
        if reason:
            log.append(f"{typ}:{value} removed ({reason})")
        else:
            kept.append((typ, value))
    return kept


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=os.path.join(ROOT, "config"))
    ap.add_argument("--out", default=os.path.join(ROOT, "build"))
    args = ap.parse_args()

    with open(os.path.join(args.config, "sources.json"), encoding="utf-8") as f:
        cfg = json.load(f)
    allow = geolib.read_rules_file(os.path.join(args.config, "allowlist.txt"))
    critical = geolib.read_hosts_file(os.path.join(args.config, "critical.txt"))

    data_dir = os.path.join(args.out, "data")
    cache_dir = os.path.join(args.out, "cache")
    os.makedirs(data_dir, exist_ok=True)
    os.makedirs(cache_dir, exist_ok=True)

    needed = sorted({s for srcs in cfg["tags"].values() for s in srcs})
    parsed, stats = {}, {"sources": {}, "tags": {}}
    for name in needed:
        src = cfg["sources"][name]
        entries, bad = geolib.PARSERS[src["format"]](fetch(src["url"], cache_dir))
        if len(entries) < src.get("min_entries", 0):
            sys.exit(f"ERROR: {name}: {len(entries)} entries < min_entries {src['min_entries']}, "
                     "источник обрезан или сменил формат")
        parsed[name] = entries
        stats["sources"][name] = {"url": src["url"], "entries": len(entries), "skipped": bad}
        print(f"source {name}: {len(entries)} entries, {bad} skipped")

    failed = False
    for tag, srcs in cfg["tags"].items():
        merged = list(dict.fromkeys(e for s in srcs for e in parsed[s]))
        log = []
        final = apply_allowlist(merged, allow, log)
        m = geolib.Matcher(final)
        hits = [(h, m.match(h)) for h in critical if m.match(h)]
        for h, rule in hits:
            print(f"CRITICAL: tag {tag} blocks {h} via {rule}", file=sys.stderr)
            failed = True
        with open(os.path.join(data_dir, tag), "w", encoding="utf-8") as f:
            f.write(f"# generated by scripts/build_lists.py from: {', '.join(srcs)}\n")
            for typ, value in sorted(final, key=lambda e: (e[0], e[1])):
                f.write(f"{typ}:{value}\n")
        with open(os.path.join(args.out, f"allowlist-{tag}.log"), "w", encoding="utf-8") as f:
            f.write("\n".join(log) + ("\n" if log else ""))
        stats["tags"][tag] = {"sources": srcs, "entries": len(final), "allowlist_removed": len(log)}
        print(f"tag {tag}: {len(final)} entries, {len(log)} removed by allowlist")

    with open(os.path.join(args.out, "stats.json"), "w", encoding="utf-8") as f:
        json.dump(stats, f, ensure_ascii=False, indent=2)
    if failed:
        sys.exit("ERROR: critical hosts are blocked, see above")


if __name__ == "__main__":
    main()
